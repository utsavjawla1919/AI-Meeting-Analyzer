def export_transcript_pdf(meeting_id: str):
    """
    GET /api/export/<meeting_id>/transcript
    Generates a transcript-only PDF (lighter, faster).
    """
    if not verify_meeting_ownership(meeting_id):
        return jsonify({"error": "Not found or access denied"}), 404

    meeting    = MeetingModel.find_by_id(current_app.db, meeting_id)
    transcript = TranscriptModel.find_by_meeting(current_app.db, meeting_id)

    if not transcript:
        return jsonify({"error": "Transcript not available"}), 404

    styles = _build_styles()
    buffer = io.BytesIO()
    doc    = SimpleDocTemplate(buffer, pagesize=A4,
                               leftMargin=2*cm, rightMargin=2*cm,
                               topMargin=2.5*cm, bottomMargin=2.5*cm)
    story  = []
    title  = meeting.get("ai_title") or meeting.get("title", "Transcript")

    story.append(Paragraph(title, styles["title"]))
    story.append(Paragraph("Meeting Transcript", styles["subtitle"]))
    story.append(HRFlowable(width="100%", thickness=1, color=BRAND_BLUE))
    story.append(Spacer(1, 12))

    if transcript.get("segments"):
        current_speaker = None
        for seg in transcript["segments"]:
            speaker = seg.get("speaker", "Unknown")
            text    = seg.get("text", "").strip()
            start   = seg.get("start", 0)
            m, s    = divmod(int(start), 60)
            if speaker != current_speaker:
                current_speaker = speaker
                story.append(Paragraph(f"{speaker}  [{m:02d}:{s:02d}]", styles["speaker"]))
            story.append(Paragraph(text, styles["segment"]))
    else:
        story.append(Paragraph(transcript.get("full_text", ""), styles["body"]))

    doc.build(story)
    buffer.seek(0)
    safe  = "".join(c for c in title if c.isalnum() or c in " _-")[:50]
    fname = f"{safe.replace(' ', '_')}_transcript.pdf"

    return send_file(buffer, mimetype="application/pdf",
                     as_attachment=True, download_name=fname)
